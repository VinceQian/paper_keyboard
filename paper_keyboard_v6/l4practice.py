# 4. 完成 components/input_decider.py
# ============================================================

# InputDecider 的作用：
# 判断 candidate 是否是一次新的输入触发。
#
# candidate 的规则：
#
# -1
#     没有触发输入
#
# 0-9
#     某个 finger_id 触发了输入
#
# 为什么不能看到 candidate 就输入？
#
# 因为一次敲击可能会持续好几帧。
# 例如：
#
# -1, 1, 1, 1, -1
#
# 这里 candidate=1 出现了三帧，但这只是一次敲击。
# 所以只能输入一次。
#
# 判断新输入的规则：
#
# 上一帧是 -1
# 当前帧不是 -1
#
# 这时才认为产生了一次新输入。
#
# 这个文件写在：
# components/input_decider.py

